# jira_notifier.py
import json
import os
from jira import JIRA
from datetime import datetime
from dotenv import load_dotenv
import glob

# Load environment variables
load_dotenv('properties.env')


class JiraNotifier:
    def __init__(self):
        """Initialize Jira connection from properties.env"""
        self.server = os.getenv('JIRA_SERVER')
        self.email = os.getenv('JIRA_EMAIL')
        self.api_token = os.getenv('JIRA_API_TOKEN')
        self.project_key = os.getenv('JIRA_PROJECT_KEY')
        self.jira = None

    def connect(self):
        """Connect to Jira"""
        try:
            self.jira = JIRA(
                server=self.server,
                basic_auth=(self.email, self.api_token)
            )
            print("Connected to Jira")

            # Check if project exists - STOP if it doesn't
            if not self.ensure_project_exists():
                return False  # Don't continue without valid project

            return True
        except Exception as e:
            print(f"Jira connection failed: {e}")
            return False

    def ensure_project_exists(self):
        """Check if project exists"""
        try:
            project = self.jira.project(self.project_key)
            print(f"Using project: '{project.name}' ({self.project_key})")
            return True
        except:
            print(f"\n### ERROR: Project '{self.project_key}' does not exist!\n")
            print("Please create the project manually:")
            print("  1. Go to your Jira → Projects → Create Project")
            print("  2. Choose project template (Kanban/Scrum)")
            print("  3. Name it. e.g: QA Captain Fix")
            print(f"  4. Use project key: First letters of your project name words. (e.g: QCF)")
            print("  5. Update properties.env file lines: JIRA_PROJECT_KEY= ... ")
            print("  6. Then run this script again.\n")
            return False


    def process_test_results(self, results_json_path, test_plan_json_path):
        """Main method to process results and create Jira issues"""

        # Load results and test plan
        with open(results_json_path, 'r') as f:
            results_data = json.load(f)

        with open(test_plan_json_path, 'r') as f:
            plan_data = json.load(f)

        # Extract test plan from nested structure
        test_plan = plan_data.get('testPlan', plan_data)

        if not self.connect():
            return False

        # Create Epic for the test execution
        epic = self.create_test_epic(results_data, test_plan)

        # Create issues for failed tests only
        failed_tests = [test for test in results_data['test_results'] if test['status'] == 'FAIL']

        if not failed_tests:
            print("No failed tests - no Jira issues needed")
            return True

        print(f"Creating {len(failed_tests)} Jira issues for failed tests...")

        created_issues = []
        for failed_test in failed_tests:
            issue = self.create_failed_test_issue(failed_test, results_data['websiteUrl'], test_plan, epic)
            if issue:
                created_issues.append({
                    'test_id': failed_test['testId'],
                    'jira_key': issue.key,
                    'jira_url': f"{self.server}/browse/{issue.key}"
                })

        # Save Jira integration results
        self.save_jira_results(epic, created_issues)

        print(f"Created {len(created_issues)} Jira issues")
        return True

    def create_test_epic(self, results_data, test_plan):
        """Create Epic for overall test execution with essential information"""
        try:
            website = results_data['websiteUrl']
            timestamp = datetime.now().strftime('%Y-%m-%d %H:%M')

            # Get failed tests summary
            failed_tests = [test for test in results_data['test_results'] if test['status'] == 'FAIL']
            failed_list = []
            if failed_tests:
                for test in failed_tests:
                    failed_list.append(f"- {test['testId']}: {test['testName']} - {test['error']}")

            # Calculate total duration
            total_duration = sum(test['duration'] for test in results_data['test_results'])

            description = f"""
    AUTOMATED QA TEST EXECUTION REPORT
    {'=' * 40}

    WEBSITE: {website}
    EXECUTION TIME: {timestamp}
    TOTAL DURATION: {total_duration:.2f} seconds

    TEST RESULTS:
    - Total Tests: {results_data['total_tests']}
    - Passed: {results_data['passed']}
    - Failed: {results_data['failed']}
    - Pass Rate: {results_data['pass_rate']}

    FAILED TESTS:
    {chr(10).join(failed_list) if failed_list else 'No failed tests - All tests passed!'}


    This comprehensive report was auto-generated by QA Captain.
    For questions or issues, please review the individual test case tickets linked to this epic.
            """.strip()

            # Create summary
            status_indicator = "FAILED" if results_data['failed'] > 0 else "PASSED"
            summary = f"[{status_indicator}] QA Test: {test_plan.get('websiteAnalysis', {}).get('title', 'Website')} - {datetime.now().strftime('%Y-%m-%d')}"

            issue_dict = {
                'project': {'key': self.project_key},
                'summary': summary,
                'description': description,
                'issuetype': {'name': 'Bug'}
            }
            epic = self.jira.create_issue(fields=issue_dict)
            print(f"Created Task: {epic.key}")
            return epic

        except Exception as e:
            print(f"Failed to create Epic: {e}")
            return None


    def create_failed_test_issue(self, failed_test, website_url, test_plan, epic=None):
        """Create detailed Jira issue for a single failed test case"""
        try:
            # Find the corresponding test case details from the plan (inline)
            test_case_details = {}
            try:
                for suite in test_plan.get('testSuites', []):
                    for test_case in suite['testCases']:
                        if test_case['testId'] == failed_test['testId']:
                            test_case_details = test_case.copy()
                            test_case_details['suiteName'] = suite['suiteName']
                            test_case_details['suiteType'] = suite['suiteType']
                            break
            except:
                test_case_details = {}

            # Extract additional details
            expected_result = test_case_details.get('expectedResult', 'Not specified')
            test_description = test_case_details.get('description', 'No description available')
            test_steps = test_case_details.get('steps', [])
            test_priority = test_case_details.get('priority', 'medium')
            page_url = test_case_details.get('pageUrl', website_url)
            suite_name = test_case_details.get('suiteName', 'Unknown Suite')
            suite_type = test_case_details.get('suiteType', 'Unknown')

            # Format test steps for reproduction
            formatted_steps = []
            for i, step in enumerate(test_steps, 1):
                formatted_steps.append(f"{i}. {step}")

            # Determine failure severity (inline logic)
            error_lower = failed_test['error'].lower()
            if any(keyword in error_lower for keyword in ['timeout', 'not found', 'no such element']):
                severity = 'HIGH'
            elif any(keyword in error_lower for keyword in ['failed at step', 'navigation', 'click']):
                severity = 'MEDIUM'
            elif any(keyword in error_lower for keyword in ['warning', 'minor']):
                severity = 'LOW'
            else:
                severity = 'MEDIUM'

            # Classify error type (inline logic)
            if 'timeout' in error_lower:
                error_type = 'Timeout Error'
            elif 'no such element' in error_lower or 'not found' in error_lower:
                error_type = 'Element Not Found'
            elif 'navigation' in error_lower or 'page' in error_lower:
                error_type = 'Navigation/Page Load Error'
            elif 'click' in error_lower:
                error_type = 'Interaction Error'
            elif 'step' in error_lower:
                error_type = 'Test Step Execution Error'
            else:
                error_type = 'General Test Execution Error'

            # Suggest likely cause (inline logic)
            if 'navigation' in error_lower or 'page' in error_lower:
                likely_cause = 'Page may not be loading correctly or URL is incorrect'
            elif 'not found' in error_lower or 'no such element' in error_lower:
                likely_cause = 'Web element may have changed or page structure modified'
            elif 'timeout' in error_lower:
                likely_cause = 'Page loading too slowly or element not appearing in time'
            elif 'click' in error_lower:
                likely_cause = 'Element may not be clickable or obscured by other elements'
            else:
                likely_cause = 'Test logic may need review or website functionality changed'

            # Determine environment type (inline logic)
            if 'localhost' in website_url or '127.0.0.1' in website_url:
                environment = 'Local Development'
            elif 'file:///' in website_url:
                environment = 'Local File System'
            elif any(env in website_url for env in ['dev', 'test', 'staging']):
                environment = 'Test/Staging Environment'
            else:
                environment = 'Production/Live Environment'

            # Build comprehensive description
            description = f"""
    BUG REPORT - TEST FAILURE
    {'=' * 30}

    BASIC INFORMATION:
    - Test ID: {failed_test['testId']}
    - Test Name: {failed_test['testName']}
    - Test Suite: {suite_name} ({suite_type})
    - Priority Level: {test_priority.upper()}
    - Failure Severity: {severity}

    EXECUTION DETAILS:
    - Website: {website_url}
    - Specific Page: {page_url}
    - Execution Time: {failed_test['executed_at']}
    - Test Duration: {failed_test.get('duration', 0):.2f} seconds
    - Environment: {environment}

    TEST CASE DESCRIPTION:
    {test_description}

    EXPECTED RESULT:
    {expected_result}

    ACTUAL RESULT (ERROR):
    {failed_test.get('error', 'No error message available')}

    REPRODUCTION STEPS:
    {chr(10).join(formatted_steps) if formatted_steps else 'Steps not available'}

    FAILURE ANALYSIS:
    - Error Type: {error_type}
    - Likely Cause: {likely_cause}
    - Impact: This failure prevents the test case from completing successfully

    EVIDENCE AND ATTACHMENTS:
    - Screenshot: {failed_test.get('screenshot', 'Not available')}
    - Additional logs: Check test execution logs for more details

    RECOMMENDED ACTIONS:
    1. Review the error message and screenshot
    2. Verify the website/page is accessible
    3. Check if the expected elements exist on the page
    4. Test manually to reproduce the issue
    5. Fix the underlying issue
    6. Re-run the automated test to verify the fix

    This issue was automatically created by QA Captain Fix Team.
    Please investigate and resolve this test failure promptly.

    Related Epic: {epic.key if epic else 'Not linked'}
            """.strip()

            # Create more descriptive summary with priority and severity
            priority_indicator = test_priority.upper()[:1]  # H, M, L
            summary = f"[{priority_indicator}] [{severity}] Test Failure: {failed_test['testName']} - {failed_test['testId']}"

            issue_dict = {
                'project': {'key': self.project_key},
                'summary': summary,
                'description': description,
                'issuetype': {'name': 'Bug'}
            }

            # Create the issue
            issue = self.jira.create_issue(fields=issue_dict)

            # Attach screenshot if available
            self.attach_evidence(issue, failed_test)

            print(f"Created detailed failure issue: {issue.key}")
            return issue

        except Exception as e:
            print(f"Failed to create issue for {failed_test['testId']}: {e}")
            return None


    def attach_evidence(self, issue, failed_test):
        """Attach screenshot evidence to Jira issue"""
        try:
            screenshot_path = failed_test.get('screenshot')
            if screenshot_path and os.path.exists(screenshot_path):
                with open(screenshot_path, 'rb') as screenshot_file:
                    self.jira.add_attachment(
                        issue=issue,
                        attachment=screenshot_file,
                        filename=f"screenshot_{failed_test['testId']}.png"
                    )
                print(f"Screenshot attached to {issue.key}")
            else:
                print(f"No screenshot found for {failed_test['testId']}")
        except Exception as e:
            print(f"Failed to attach screenshot: {e}")

    def save_jira_results(self, epic, created_issues):
        """Save Jira integration results to file"""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        jira_results = {
            'integration_timestamp': timestamp,
            'epic': {
                'key': epic.key if epic else None,
                'url': f"{self.server}/browse/{epic.key}" if epic else None
            },
            'failed_test_issues': created_issues,
            'summary': {
                'total_issues_created': len(created_issues),
                'epic_created': epic is not None
            }
        }

        os.makedirs('generated_files/Jira', exist_ok=True)
        results_file = f"generated_files/Jira/jira_integration_{timestamp}.json"
        with open(results_file, 'w') as f:
            json.dump(jira_results, f, indent=2)

        print(f"Jira integration results saved: {results_file}")


def run_jira_integration(results_json, test_plan_json):
    """Main function to run Jira integration"""
    print("Starting Jira Integration...")

    # Check if files exist
    if not os.path.exists(results_json):
        print(f"Results file not found: {results_json}")
        return False

    if not os.path.exists(test_plan_json):
        print(f"Test plan file not found: {test_plan_json}")
        return False

    # Run the integration
    notifier = JiraNotifier()
    success = notifier.process_test_results(results_json, test_plan_json)

    if success:
        print("Jira integration completed successfully!")
    else:
        print("Jira integration failed!")

    return success


def main():

    # Find newest .json file in generated_files/plans folder
    plans_folder = "generated_files/plans"
    json_files = glob.glob(os.path.join(plans_folder, "*.json"))

    if json_files:
        # Sort by creation time (newest last) and take the newest
        json_files.sort(key=os.path.getctime, reverse=True)
        plan_file = json_files[0]
        print(f"Using latest test plan: {plan_file}")

        #after finding the plan file, checking for the result file...
        # Find newest .json file in generated_files/results folder
        results_folder = "generated_files/results"
        json_files = glob.glob(os.path.join(results_folder, "*.json"))
        if json_files:
            # Sort by creation time (newest last) and take the newest
            json_files.sort(key=os.path.getctime, reverse=True)
            result_file = json_files[0]
            print(f"Using latest result file: {result_file}")

            #both files are found
            run_jira_integration(result_file, plan_file)
        else:
            print("No JSON files found in generated_files/results folder.")
            return

    else:
        print("No JSON files found in generated_files/plans folder.")
        return


if __name__ == "__main__":
    main()